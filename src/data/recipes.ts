import type { IngredientRole, MealType, Recipe } from '../types/models';

type Ing = [foodId: string, grams: number, role: IngredientRole];

function R(id: string, name: string, mealTypes: MealType[], prepMinutes: number, ings: Ing[], steps: string[]): Recipe {
  return {
    id,
    name,
    mealTypes,
    prepMinutes,
    ingredients: ings.map(([foodId, grams, role]) => ({ foodId, grams, role })),
    steps,
  };
}

